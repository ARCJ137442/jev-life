/**
 * 部署期配置：远端免费试用端点的地址。
 *
 * ═══ 为什么它不写在 `api.ts` 里、也不给默认值 ═══
 *
 * 纯静态托管（GitHub Pages、任意静态空间、`file://`）没有同源的服务端函数，
 * 所以「免费试用」类后端必须指向别处 —— 也就是 Vercel 上的那份部署，而那里
 * 才是密钥所在（静态页面只发请求，拿不到任何凭据）。
 *
 * 但**这个地址不能由仓库提供默认值**。原因很具体：
 *
 * > 若仓库里写死一个默认域名，别人的 fork 部署到静态托管之后，会把每一个
 * > 决策请求发到**原作者**的部署上，消耗**原作者**的额度 —— 而他这边
 * > 界面一切正常，看不到任何异常。
 *
 * 靠注释写「请改成你的域名」是**君子协议**：它要求每个 fork 的人守规矩，
 * 而项目的立场一向是**判据不能依赖人的自觉**（见 `DESIGN.md` 第五节那句
 * 「找不到 ≠ 没有」，以及密钥一律不给默认值那条）。
 *
 * 所以这里的默认值是**空字符串**：
 *   - 空 → 静态托管下**没有可用的远端后端**，界面应当把「免费试用」那几条
 *     隐藏或置灰，而不是发一个注定 404 的请求
 *   - 填了 → 才走跨域调用
 *
 * ═══ 怎么配 ═══
 *
 * 本机（`localhost`）与 Vercel **都不需要它** —— 那两种形态下代理是同源的。
 * 只有纯静态托管需要。
 *
 *   - **GitHub Pages**：在仓库 Settings → Secrets and variables → Actions →
 *     Variables 里加一个 `JEV_LIFE_REMOTE_BASE`，`pages.yml` 会在编译前
 *     把它写进这个文件
 *   - **其他静态空间**：直接改这个文件，或者在你的构建流程里做同样的事
 *
 * ⚠ 如果你**不打算**跑任何「免费试用」后端，保持它是空的即可 ——
 * 使用者仍然可以在「API」抽屉里自备密钥直连上游。
 */
export const REMOTE_PROXY_BASE = "";

/**
 * 静态托管下是否真的能用到远端后端。
 *
 * **界面应当用它来决定要不要显示「免费试用」那几条**，而不是让用户点进去
 * 才发现 404。空地址 + 静态托管 = 那条路根本走不通。
 */
export function hasRemoteProxy(): boolean {
  return REMOTE_PROXY_BASE.trim() !== "";
}
